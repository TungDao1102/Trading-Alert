# --- append-only and terminal-state triggers (D-10, D-20) -----------------------------
# Triggers and functions are not ORM objects; plan 07 asserts them from pg_trigger. The
# table owner can still DISABLE TRIGGER: owner-vs-app role separation is deferred (Phase 26).
_APPEND_ONLY_FUNCTION = """
CREATE FUNCTION reject_append_only_mutation() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only (% blocked)', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'P0001';
END
$$
"""

# TG_ARGV[0] is the status column; TG_ARGV[1..] are the terminal values. The old and new
# values are read through to_jsonb so ONE function serves tables with different column names.
_TERMINAL_FUNCTION = """
CREATE FUNCTION reject_terminal_status_change() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    old_status text := to_jsonb(OLD) ->> TG_ARGV[0];
    new_status text := to_jsonb(NEW) ->> TG_ARGV[0];
    i integer;
BEGIN
    IF old_status IS DISTINCT FROM new_status THEN
        FOR i IN 1 .. TG_NARGS - 1 LOOP
            IF old_status = TG_ARGV[i] THEN
                RAISE EXCEPTION '%.% is terminal (% -> % blocked)',
                    TG_TABLE_NAME, TG_ARGV[0], old_status, new_status
                    USING ERRCODE = 'P0001';
            END IF;
        END LOOP;
    END IF;
    RETURN NEW;
END
$$
"""


