def _drop_triggers() -> None:
    for table in (
        "execution_intents",
        "approvals",
        "positions",
        "orders",
        "trade_plans",
        "signals",
    ):
        op.execute(f"DROP TRIGGER trg_{table}_terminal_status ON {table}")
    for table in ("plan_constraint_snapshots", "system_state_events", "journal_events"):
        op.execute(f"DROP TRIGGER trg_{table}_no_truncate ON {table}")
        op.execute(f"DROP TRIGGER trg_{table}_append_only ON {table}")
    op.execute("DROP FUNCTION reject_terminal_status_change()")
    op.execute("DROP FUNCTION reject_append_only_mutation()")


