"""JSON loaders of the Phase 22 recorded-Demo fixtures (plan 22-01).

The fixtures under `tests/fixtures/phase22/recorded_demo/` are generated by
`scripts/gen_phase22_fixtures.py` from the owner-run Demo capture of 2026-10-22 (RECORDED_DEMO,
demo-observed, not mainnet). The loaders return the parsed JSON; `demo_brackets()` (plan 22-07)
is the one helper that builds a pure `src.risk.liquidation.Bracket` list from it, so tests never
type a bracket value.
"""

from __future__ import annotations

import json
from decimal import Decimal
from pathlib import Path
from typing import Any

from src.risk.liquidation import Bracket

RECORDED_DEMO = Path(__file__).resolve().parent.parent / "fixtures" / "phase22" / "recorded_demo"


def _load(name: str) -> Any:
    return json.loads((RECORDED_DEMO / name).read_text(encoding="utf-8"))


def load_symbol_config() -> list[dict[str, Any]]:
    """The recorded `GET /fapi/v1/symbolConfig` answer: one BTCUSDT row (CROSSED, leverage 20)."""
    value: list[dict[str, Any]] = _load("symbol_config.json")
    return value


def load_leverage_brackets() -> list[dict[str, Any]]:
    """The recorded `GET /fapi/v1/leverageBracket` answer: one BTCUSDT entry, ten brackets."""
    value: list[dict[str, Any]] = _load("leverage_brackets.json")
    return value


def demo_brackets() -> list[Bracket]:
    """The ten recorded Demo brackets as pure `Bracket` objects (demo-observed, not mainnet).

    Every number is read from the generated fixture JSON text as a Decimal (`parse_float`), never
    through a binary float.
    """
    text = (RECORDED_DEMO / "leverage_brackets.json").read_text(encoding="utf-8")
    entries = json.loads(text, parse_float=Decimal)
    (entry,) = entries
    return [
        Bracket(
            bracket=int(row["bracket"]),
            initial_leverage=int(row["initialLeverage"]),
            notional_floor=Decimal(str(row["notionalFloor"])),
            notional_cap=Decimal(str(row["notionalCap"])),
            maint_margin_ratio=Decimal(str(row["maintMarginRatio"])),
            cum=Decimal(str(row["cum"])),
        )
        for row in entry["brackets"]
    ]
