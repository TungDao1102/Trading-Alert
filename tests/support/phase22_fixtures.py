"""JSON loaders of the Phase 22 recorded-Demo fixtures (plan 22-01).

The fixtures under `tests/fixtures/phase22/recorded_demo/` are generated by
`scripts/gen_phase22_fixtures.py` from the owner-run Demo capture of 2026-10-22 (RECORDED_DEMO,
demo-observed, not mainnet). This module only loads the parsed JSON: it imports nothing from the
project, so later plans can serve the same payloads to any fake.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

RECORDED_DEMO = Path(__file__).resolve().parent.parent / "fixtures" / "phase22" / "recorded_demo"


def _load(name: str) -> Any:
    return json.loads((RECORDED_DEMO / name).read_text(encoding="utf-8"))


def load_symbol_config() -> list[dict[str, Any]]:
    """The recorded `GET /fapi/v1/symbolConfig` answer: one BTCUSDT row (CROSSED, leverage 20)."""
    value: list[dict[str, Any]] = _load("symbol_config.json")
    return value


def load_leverage_brackets() -> list[dict[str, Any]]:
    """The recorded `GET /fapi/v1/leverageBracket` answer: one BTCUSDT entry, ten brackets."""
    value: list[dict[str, Any]] = _load("leverage_brackets.json")
    return value
