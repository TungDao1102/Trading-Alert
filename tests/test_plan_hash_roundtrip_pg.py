"""Real planner output through PostgreSQL: plan_hash reproduction and the precision guard (17-10).

The plan_hash is what an approval re-verifies before an order is placed (APRV-02), so a plan that
leaves the database even one digit different from the plan that was approved would silently
break the approval binding (F-410). This module takes plans from the REAL planner on the
baseline-v6 sets (Phase 15, D-19: trend-pullback on the confirmed-pivot window, breakout-retest
on the anchored retest windows and range-mr on the pivot-NEUTRAL windows of
`tests/geometry_builders.py`, both directions for Families B and C), inserts them through
`PgTradingEntityStore`, reads them back and recomputes `_plan_hash` from the read-back fields:

  - the recomputed hash equals the stored hash for every plan and for several account sizes (the
    quantity columns take values with up to 18 fractional digits);
  - every read-back Decimal equals the original, and its canonical text equals the original's;
  - the three plans in `tests/fixtures/phase4/expected_plans.json` (a regression snapshot,
    regenerated by scripts/_regen_phase4_expectations.py from the same windows and sets) have
    the snapshot hash;
  - a plan whose entry price carries 19 fractional digits is refused with `PrecisionError`
    (the guard), while an integer-part overflow is a typed `StoreFailure` (17-REVIEW WR-01).

If the hash test fails, the defect is in plan 17-05's quantization or in the store, and must be
reported, not masked.
"""

